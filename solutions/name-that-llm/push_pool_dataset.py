# Publish extra/pool_v2.parquet as a Kaggle dataset so a training kernel can attach it.
# `kaggle datasets create` posts to www.googleapis.com, which is unreachable from here;
# rewrite that host to storage.googleapis.com first (same trick as kaggle_submit.py).
import json
from pathlib import Path

GCS_OLD = "www.googleapis.com"
GCS_NEW = "storage.googleapis.com"
STAGE = Path(__file__).resolve().parent / "extra" / "publish" / "ntl-pool-v2"
DS_ID = "ibillxia/ntl-pool-v2"
POOL = Path(__file__).resolve().parent / "extra" / "pool_v2.parquet"


def patch_gcs_host():
    import requests
    original = requests.Session.request

    def request(self, method, url, *a, **kw):
        if GCS_OLD in str(url) and "/upload/storage/" in str(url):
            url = str(url).replace(GCS_OLD, GCS_NEW)
            self.trust_env = False
        return original(self, method, url, *a, **kw)

    requests.Session.request = request


def main():
    STAGE.mkdir(parents=True, exist_ok=True)
    (STAGE / "pool_v2.parquet").write_bytes(POOL.read_bytes())
    summary = json.loads((POOL.with_name("pool_v2_summary.json")).read_text())
    (STAGE / "dataset-metadata.json").write_text(json.dumps({
        "title": "NTL pool v2",
        "id": DS_ID,
        "licenses": [{"name": "CC-BY-4.0"}],
        "description": (
            "Stage-1 corpus for the name-that-llm competition: the public in-style pool "
            "(prvsiyan/ntl-public-in-style-pool-v1) plus the forum corpora that are not already in it, "
            f"deduplicated and filtered with typographic invariants. rows={summary['rows']}. "
            "All rows come from public CC BY 4.0 datasets generated by the competition models through "
            "official or first-party APIs."
        ),
    }, indent=2), encoding="utf-8")

    patch_gcs_host()
    from kaggle.api.kaggle_api_extended import KaggleApi
    api = KaggleApi()
    api.authenticate()
    refs = [d.ref for d in api.datasets_list(mine=True)] if hasattr(api, "datasets_list") else []
    if DS_ID in refs:
        print(api.dataset_create_version(str(STAGE), "pool v2", quiet=False, dir_mode="skip"))
    else:
        print(api.dataset_create_new(str(STAGE), public=False, quiet=False, dir_mode="skip"))


if __name__ == "__main__":
    main()
