"""Render the human-readable comparison report."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, List

from gda import paths
from gda.rubric import WEIGHTS


def _pct(x) -> str:
    return "n/a" if x is None else f"{float(x):.1%}"


def _table(headers: List[str], rows: List[List[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def build_report(payload: Dict) -> str:
    cands = payload["candidates"]
    best = next(c for c in cands if c["name"] == payload["best"])

    lines: List[str] = []
    add = lines.append

    add("# Gemma 4 Developer Agent — candidate comparison\n")
    add("This report compares agent-configuration candidates for "
        "[`gemma-4-developer-agent`](https://www.kaggle.com/competitions/gemma-4-developer-agent). "
        "It is generated by `solutions/gemma_4_developer_agent` and is fully "
        "reproducible from the repository.\n")

    add("> **What is and is not measured here.** The official score is the "
        "percentage of hidden repository issues whose validation tests pass "
        "after applying the submitted patch. Producing that number requires the "
        "organiser's harness: a Docker sandbox, the `gemma-4-31b-it-qat-w4a16-ct` "
        "weights and the hidden task set. None of that is available offline, so "
        "**no candidate here has an official score, and none is claimed.** What "
        "this package does measure is (a) whether a candidate survives the "
        "harness's *upload gates* and (b) how well its engineering matches the "
        "failure modes the competition itself documents. Section 5 states the "
        "limits of that substitution explicitly.\n")

    # ---------------- 1. result ------------------------------------------
    add("## 1. Result\n")
    add(f"**Selected: `{best['name']}`** — composite **{best['composite']:.3f}** "
        f"(rubric {best['rubric']['score_10']:.2f}/10, "
        f"proxy {_pct(best['proxy']['score'])}, "
        f"{'compiles' if best['compliant'] else 'REJECTED'}).\n")
    add(f"> {best['idea']}\n")
    add(f"Artefact: `{payload['best_zip']}`\n")

    add(_table(
        ["rank", "candidate", "composite", "rubric /10", "proxy", "compiles",
         "hard fails"],
        [
            [i, f"`{c['name']}`", f"{c['composite']:.3f}",
             f"{c['rubric']['score_10']:.2f}",
             _pct(c["proxy"]["score"]),
             "yes" if c["compliant"] else "**NO**",
             ", ".join(c["hard_failures"]) or "—"]
            for i, c in enumerate(cands, 1)
        ],
    ))
    add("")

    # ---------------- 2. the ladder --------------------------------------
    add("## 2. The candidate ladder\n")
    add("Each candidate adds exactly one engineering idea, so the comparison "
        "reads as an ablation rather than as five random prompts.\n")
    add(_table(["candidate", "idea", "failure boundary it addresses"],
               [[f"`{c['name']}`", c["idea"], c["delta"]] for c in cands]))
    add("")

    # ---------------- 3. gates -------------------------------------------
    add("## 3. Harness gates\n")
    add("These mirror the checks the released `adk-submission` validator performs "
        "before an upload is accepted. A hard failure means the zip cannot be "
        "uploaded at all — the observed symptom is a bare *Notebook Threw "
        "Exception* with no traceback.\n")
    gate_ids: List[str] = []
    for c in cands:
        for chk in c["checks"]:
            if chk["id"] not in gate_ids:
                gate_ids.append(chk["id"])
    by_cand = {c["name"]: {chk["id"]: chk for chk in c["checks"]} for c in cands}
    rows = []
    for g in gate_ids:
        levels = {by_cand[c["name"]].get(g, {}).get("level", "—") for c in cands}
        level = "hard" if "hard" in levels else "soft"
        cells = []
        for c in cands:
            chk = by_cand[c["name"]].get(g)
            cells.append("—" if chk is None else ("pass" if chk["passed"] else "**FAIL**"))
        rows.append([f"`{g}`", level, *cells])
    add(_table(["gate", "level", *[f"`{c['name']}`" for c in cands]], rows))
    add("")

    detail = [c for c in cands if c["soft_warnings"] or c["hard_failures"]]
    if detail:
        add("Gate findings that need a decision:\n")
        for c in detail:
            add(f"- **`{c['name']}`**")
            for chk in c["checks"]:
                if not chk["passed"]:
                    add(f"  - `{chk['id']}` ({chk['level']}): {chk['detail']}")
        add("")

    # ---------------- 4. rubric ------------------------------------------
    add("## 4. Rubric decomposition\n")
    add(_table(
        ["dimension", "weight", *[f"`{c['name'].split('_')[0]}`" for c in cands]],
        [[f"`{d}`", f"{WEIGHTS[d]:.2f}",
          *[f"{c['rubric']['dimensions'][d]['score']:.2f}" for c in cands]]
         for d in WEIGHTS],
    ))
    add("")
    add("Where the selected candidate earns its margin:\n")
    for d in WEIGHTS:
        miss = best["rubric"]["dimensions"][d]["miss"]
        if not miss:
            add(f"- `{d}` — **full marks**: every signal present.")
    add("")

    # ---------------- 5. proxy -------------------------------------------
    add("## 5. Proxy execution — and its limits\n")
    add("For every candidate that ships executable skill scripts, the proxy "
        "runs those scripts against fixture repositories in a temp sandbox and "
        "reads the JSON they write. This is real execution, not a heuristic.\n")
    add(_table(
        ["candidate", "executed", "passed", "score"],
        [[f"`{c['name']}`", c["proxy"]["executed"], c["proxy"]["passed"],
          _pct(c["proxy"]["score"])] for c in cands],
    ))
    add("")
    add("### What the proxy cannot see\n")
    for line in [
        "It does not run the candidate's prompt against Gemma 4, so it says "
        "nothing about model behaviour, tool-call validity under 4-bit "
        "quantisation, or patch correctness on real issues.",
        "Candidates that ship no scripts are scored `n/a` rather than zero, and "
        "receive the neutral prior 0.50 in the composite. A prompt-only agent can "
        "perform well in the real harness; it simply provides nothing verifiable "
        "offline.",
        "Skill-script correctness is necessary but not sufficient: a perfect "
        "`patch_hygiene` script cannot fix a wrong hypothesis about the bug.",
        "The fixture repos are three files. They test that the machinery works, "
        "not that it generalises.",
        "**The ladder and the rubric share provenance.** The candidates were "
        "designed from the failure boundaries the rubric encodes, so the top "
        "candidate saturating the rubric is an expected consequence of that "
        "design, not independent confirmation that it will score well. The proxy "
        "is the only signal here that could have contradicted a claim -- and it "
        "did not, which is evidence about the shipped scripts and nothing more.",
    ]:
        add(f"- {line}")
    add("")

    # ---------------- 6. recommendation ----------------------------------
    add("## 6. Recommendation\n")
    add(f"Ship **`{best['name']}`**. Concretely:\n")
    add(f"1. Upload `{Path(str(payload['best_zip'])).name}` from "
        f"`artifacts/` — it passes every hard gate.\n")
    add("2. Rerun the gate checks after any edit: "
        "`python -m gda.cli validate`.\n")
    add("3. The single largest remaining lever is **not** in this package: "
        "training a LoRA adapter on the released task graph and dropping it into "
        "`adapters/main_lora/`, then referencing `adapter: main_lora` on the root "
        "agent. The builder already supports this — see the README.\n")
    add("4. Do not treat the composite ordering as a leaderboard. It orders "
        "*engineering quality*; only the harness can order *task pass rate*.\n")

    add("---\n")
    add("### Reproduce\n")
    add("```bash\n"
        "cd solutions/gemma_4_developer_agent\n"
        "python -m gda.cli all          # build + validate + score + report\n"
        "python -m gda.cli show         # print the ranking\n"
        "```\n")
    return "\n".join(lines)


def write_report(payload: Dict) -> Path:
    text = build_report(payload)
    paths.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    path = paths.REPORTS_DIR / "REPORT.md"
    path.write_text(text, encoding="utf-8")
    (paths.ARTIFACTS_DIR / "comparison_summary.json").write_text(
        json.dumps({k: v for k, v in payload.items() if k != "candidates"},
                   indent=2, ensure_ascii=False), encoding="utf-8")
    return path
